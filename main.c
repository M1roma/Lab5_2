/**
 * @brief Обчислює значення математичної функції f(x) = x / (x + 2)^2.
 *
 * @param x Значення аргументу (дійсне число).
 * @return  Значення функції f(x).
 */
double f(double x) {
    return x / ((x + 2.0) * (x + 2.0));
}
