#include <stdio.h>
#include <stdlib.h>

// =========================================================================
// |                       МАТЕМАТИЧНА ФУНКЦІЯ                             |
// =========================================================================

/**
 * @brief Обчислює значення математичної функції f(x) = x / (x + 2)^2.
 *
 * @param x Значення аргументу (дійсне число).
 * @return  Значення функції f(x).
 */
double f(double x) {
    return x / ((x + 2.0) * (x + 2.0));
}

// =========================================================================
// |   Реалізація математичної функції                                     |
// ========================================================================= 
  
int main() {
// Оголошення змінних для вхідних параметрів табулювання
 double x_start = 0.0;    // Початкове значення аргументу x
 double x_end = 0.0;      // Кінцеве значення аргументу x
 double step = 0.0 ;      // Крок зміни аргументу
 int points_count = 0.0;  // Кількість точок обчислення  
 // Символьні масиви для збереження даних
 char group[50];           // Шифр навчальної групи
 char student_name[100];   // Прізвище та ім'я студента

    // Читання вхідних даних із текстового файлу input.txt
    FILE *in_file = fopen("input.txt", "r"); 
    if (in_file == NULL) { 
        printf("Error: Cannot open input.txt!\n");
        return 1; 
    }

// Послідовно зчитуємо числові параметри з файлу за допомогою fscanf
    fscanf(in_file, "%lf", &x_start);
    fscanf(in_file, "%lf", &x_end);
    fscanf(in_file, "%d", &points_count);
    fscanf(in_file, "%lf", &step);

    // Зчитуємо рядки тексту до символу переходу на новий рядок (\n)
    fscanf(in_file, " %[^\n]", group);
    fscanf(in_file, " %[^\n]", student_name);

    //закриваємо файл 
    fclose(in_file);

    // Створення текстового та бінарного файлів і запис результатів 
    // "w"  - створити/перезаписати текстовий файл для запису
    // "wb" - створити/перезаписати двійковий (бінарний) файл для запису
    FILE *out_txt = fopen("output.txt", "w");
    FILE *out_bin = fopen("data.bin", "wb");

    // Перевіряємо, чи вдалося створити обидва файли
    if (out_txt == NULL || out_bin == NULL) {
        printf("Error: Cannot create output files!\n");
        return 1;
    }

    // Форматований запис шапки таблиці у текстовий файл
    fprintf(out_txt, "+-------+--------------+--------------+\n");
    fprintf(out_txt, "|   #   |      x       |     f(x)     |\n");
    fprintf(out_txt, "+-------+--------------+--------------+\n");

    // Неформатований запис у бінарний файл: першим записуємо кількість точок N (4 байти)
    // Аргументи fwrite: (адреса даних, розмір 1 елемента, кількість елементів, потік файлу)
    fwrite(&points_count, sizeof(int), 1, out_bin);

    // Цикл табулювання функції та паралельного запису у два файли
    double x = x_start;
    for (int i = 0; i < points_count; i++) {
        double y = f(x); // Обчислюємо значення функції в поточній точці

        // Записуємо рядок таблиці у текстовий файл у читабельному вигляді
        fprintf(out_txt, "| %5d | %12.6lf | %12.6lf |\n", i + 1, x, y);

        // Записуємо байти аргументу x (8 байт) та функції y (8 байт) у бінарний файл
        fwrite(&x, sizeof(double), 1, out_bin);
        fwrite(&y, sizeof(double), 1, out_bin);

        x += step; // Збільшуємо аргумент на величину кроку
    }

    // Записуємо нижню межу таблиці та інформацію про студента у текстовий файл
    fprintf(out_txt, "+-------+--------------+--------------+\n");
    fprintf(out_txt, "Group: %s\n", group);
    fprintf(out_txt, "Student: %s\n", student_name);

    // Закриваємо обидва вихідні файли (дані остаточно зберігаються на диск)
    fclose(out_txt);
    fclose(out_bin);

    // Читання даних із бінарного файлу у динамічний масив розміром 2N
    // Відкриваємо бінарний файл у режимі читання ("rb" - read binary)
    FILE *in_bin = fopen("data.bin", "rb");
    if (in_bin == NULL) {
        printf("Error: Cannot open data.bin for reading!\n");
        return 1;
    }

    int N = 0; // Змінна для кількості рядків, яку прочитаємо з бінарного файлу
    // Зчитуємо перше ціле число (кількість точок) з початку файлу
    fread(&N, sizeof(int), 1, in_bin);

    // Динамічно виділяємо пам'ять у купі під 2N чисел типу double (N пар x та f(x))
    double *dyn_arr = (double *)malloc(2 * N * sizeof(double));
    if (dyn_arr == NULL) {
        printf("Error: Memory allocation failed!\n");
        fclose(in_bin);
        return 1;
    }

    // Одним викликом fread зчитуємо всі 2N чисел із бінарного файлу в динамічний масив
    fread(dyn_arr, sizeof(double), 2 * N, in_bin);

    // Закриваємо бінарний файл після завершення читання
    fclose(in_bin);

   // Виведення таблиці з динамічного масиву на екран
    printf("Data successfully read from binary file (N = %d):\n\n", N);
    printf("+-------+--------------+--------------+\n");
    printf("| Point |      x       |     f(x)     |\n");
    printf("+-------+--------------+--------------+\n");

    // Проходимо по всіх N точках і дістаємо пари значень із одновимірного масиву
    for (int i = 0; i < N; i++) {
        double arg_x = dyn_arr[2 * i];     // На парних індексах (0, 2, 4...) лежать значення x
        double val_y = dyn_arr[2 * i + 1]; // На непарних індексах (1, 3, 5...) лежать значення f(x)
        printf("| %5d | %12.6lf | %12.6lf |\n", i + 1, arg_x, val_y);
    }
    printf("+-------+--------------+--------------+\n");

    // Обов'язково звільняємо виділену динамічну пам'ять, щоб не було витоку пам'яті
    free(dyn_arr);

    return 0; // Успішне завершення програми
}

